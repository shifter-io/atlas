"""The full-size synthetic data set as pure functions of its settings (SCALE-GEN-1a).

Nothing here touches a database. Every figure is a deterministic function of the seed and the
settings, so a day comes out the same whether it is generated alone or with other days, and
`plan` counts each table's rows without generating them.

IP model. Each network x country is a lane with its own block of IP indexes. Day d's daily test
uses a window of the block that starts `reuse` (30-60%, per network) of its size before the end
of day d - 1's window, so that share of a day's IPs were also seen the day before. About 2% more
are borrowed from the next country of the same network (the first positions of its window that
day), so an IP can be seen in two countries of one network. IP index n is an IPv4 address in
the reserved block 240/4 (class E) for three of every four indexes (while that space lasts) and
an IPv6 address in the documentation prefix 2001:db8::/32 otherwise; its ip_id is n + 1. No real
address is used.
"""

from __future__ import annotations

import hashlib
import json
import math
from dataclasses import dataclass
from datetime import UTC, date, datetime, time, timedelta

from model_tables import _borrowed_union as _borrowed_union
from model_tables import plan as plan

from proxy_index.estimates import compute

VERSION = 1
MASK = (1 << 64) - 1
V4_SPACE = 1 << 28
V6_OFFSET = 1 << 62
REUSE = (0.30, 0.60)  # share of a test's IPs also seen the day before (per network)
SHARED = 0.02  # extra IPs borrowed from another country of the same network
JITTER = 0.10  # a test's unique IPs vary by up to this share from day to day
UNMATCHED = 5  # per mille of IPs DB-IP cannot place (the unknown location and network)
FALLBACK_QUANTILE = 0.1  # unique IPs of a country the formula lacks: this quantile of the rest
PULSE_REQUESTS = 100
GEO_ROWS = (47, 92)  # location x network rows of one pulse run
ERROR_SHARE = 50  # one timeout per this many successes in a daily test
# Latency bins as multiples of a network's median, and their weights.
LATENCY = (0.6, 0.8, 0.9, 1.0, 1.15, 1.4, 1.9, 3.2)
WEIGHTS = (6, 14, 18, 22, 16, 12, 8, 4)
HOSTING_EVERY = 33  # every 33rd synthetic ASN of a country is a hosting network
# Every country gets at least 31 cities and 5 ASNs (155 pairs), more than a pulse's 92 rows,
# however small its tests: DB-IP's lists do not shrink with a provider's pool in the country.
MIN_CITIES, MIN_ASNS = 31, 5


def mix(value: int) -> int:
    """splitmix64: a fast, well-spread 64-bit hash of an integer (used per row)."""
    value = (value + 0x9E3779B97F4A7C15) & MASK
    value = ((value ^ (value >> 30)) * 0xBF58476D1CE4E5B9) & MASK
    value = ((value ^ (value >> 27)) * 0x94D049BB133111EB) & MASK
    return value ^ (value >> 31)


def key(*parts) -> int:
    """A 64-bit hash of a tuple of labels (used per entity, not per row)."""
    text = json.dumps(parts, separators=(",", ":"), default=str)
    return int.from_bytes(hashlib.sha256(text.encode()).digest()[:8], "big")


def unit(*parts) -> float:
    return key(*parts) / 2**64


def skewed(value: int, size: int) -> int:
    """An index below `size`; small indexes far more often, like city and ASN shares."""
    share = (value & 0xFFFFFFFF) / 2**32
    return min(size - 1, int(size * share * share))


def address(n: int) -> str:
    """The synthetic address of IP index n (ip_id n + 1); distinct for every n."""
    quarter, rest = divmod(n, 4)
    v4 = quarter * 3 + rest
    if rest < 3 and v4 < V4_SPACE:
        v4 += 0xF0000000
        return f"{v4 >> 24}.{(v4 >> 16) & 255}.{(v4 >> 8) & 255}.{v4 & 255}"
    v6 = V6_OFFSET + n
    return "2001:db8::" + ":".join(f"{(v6 >> shift) & 0xFFFF:x}" for shift in (48, 32, 16, 0))


def apportion(total: int, weights) -> list[int]:
    """Split total over the weights, largest remainders first (ties to the earlier weight)."""
    whole = sum(weights)
    shares = [total * w // whole for w in weights]
    order = sorted(range(len(weights)), key=lambda i: (-(total * weights[i] % whole), i))
    for i in order[: total - sum(shares)]:
        shares[i] += 1
    return shares


@dataclass(frozen=True)
class Settings:
    seed: int
    networks: tuple[str, ...]
    countries: tuple[str, ...]
    days: int
    end_date: date
    scale: float = 1.0

    def to_json(self) -> dict:
        return {
            "version": VERSION,
            "seed": self.seed,
            "networks": list(self.networks),
            "countries": list(self.countries),
            "days": self.days,
            "end_date": self.end_date.isoformat(),
            "scale": self.scale,
        }

    @classmethod
    def from_json(cls, value: dict) -> Settings:
        if value.get("version") != VERSION:
            raise ValueError("The database was generated by another generator version")
        return cls(
            value["seed"],
            tuple(value["networks"]),
            tuple(value["countries"]),
            value["days"],
            date.fromisoformat(value["end_date"]),
            value["scale"],
        )

    def day_start(self, day: int) -> datetime:
        """00:00 UTC of day 1..days; the last day ends at end_date 00:00."""
        return datetime.combine(self.end_date - timedelta(days=self.days - day + 1), time(), UTC)


@dataclass(frozen=True, slots=True)
class Lane:
    position: int  # lane order: pool position, daily run order
    network: int  # network order (product_id - 1)
    country: int  # country order
    hour: int  # the daily test's UTC hour
    ips: int  # unique IPs of a daily test before the daily jitter
    ratio: float  # requests per unique IP
    reuse: float
    offset: int  # first IP index of the lane's block
    entry: dict  # the formula's country entry (a network-curve entry when it has none)


@dataclass(frozen=True, slots=True)
class Places:
    cities: int
    regions: int
    asns: int
    location: int  # location_id (= place_id) of the country's first city
    network: int  # network_id (= asn_name_id) of the country's first ASN


@dataclass(frozen=True, slots=True)
class Test:
    """One network x country daily test of one day."""

    lane: Lane
    day: int
    run_key: int
    start: int  # first window position of the lane's own IPs
    size: int  # own IPs
    borrowed: int  # IPs taken from the neighbour lane
    source: int  # first IP index of the borrowed ones
    buckets: int
    started_at: datetime
    successes: int

    @property
    def ips(self) -> int:
        return self.size + self.borrowed

    @property
    def rows(self) -> int:
        """ip_observations rows: every third IP is seen in two buckets."""
        return self.ips + (self.ips + 2) // 3

    @property
    def errors(self) -> int:
        return self.successes // ERROR_SHARE

    def indexes(self):
        own = self.lane.offset + self.start
        yield from range(own, own + self.size)
        yield from range(self.source, self.source + self.borrowed)


class Model:
    """Lanes, places and per-day tests of the settings; formulas maps network -> formula."""

    def __init__(self, settings: Settings, formulas: dict, names: dict[str, str]):
        self.settings, self.names = settings, names
        self.formulas = [formulas[network] for network in settings.networks]
        self.salt = mix(settings.seed)
        self.lanes, self.windows, offset = [], {}, 0
        for n, formula in enumerate(self.formulas):
            reuse = REUSE[0] + (REUSE[1] - REUSE[0]) * unit(settings.seed, "reuse", n)
            fallback = _fallback(formula)
            for c, country in enumerate(settings.countries):
                hour, ips, ratio, entry = self._measured(formula, country, fallback)
                lane = Lane(len(self.lanes), n, c, hour, ips, ratio, reuse, offset, entry)
                self.lanes.append(lane)
                self.windows[lane.position] = self._windows(lane)
                offset += max(sum(window) for window in self.windows[lane.position])
        self.ip_space = offset
        self.places = self._places()

    def _measured(self, formula, country, fallback):
        """The test hour, scaled unique IPs, requests per IP and formula entry of a country."""
        entry, hour = formula["countries"].get(country), formula["schedule"].get(country)
        if entry and hour is not None and entry["unique_ips"][hour] and entry["hour_factors"][hour]:
            ips, requests = entry["unique_ips"][hour], entry["requests"][hour] or 0
        else:
            curve = formula["network_curve"]
            valid = [h for h in range(24) if curve["hour_factors"][h]]
            hour = valid[key(self.settings.seed, "hour", formula["network"], country) % len(valid)]
            ips, requests = fallback
            entry = {
                "hour_factors": curve["hour_factors"],
                "daily_factor": curve["daily_factor"],
                "requests": curve["requests"],
                "curve": "network",
                "hour_basis": ["borrowed"] * 24,
            }
        scaled = max(1, round(ips * self.settings.scale))
        return hour, scaled, max(1.0, requests / ips), entry

    def _windows(self, lane: Lane) -> list[tuple[int, int]]:
        """(first position, size) of the lane's own IPs on each day, day 1 first.

        A day's window starts `reuse` of its size before the previous window's end, so exactly
        that share of the day's own IPs (rounded) were also seen the day before.
        """
        windows, end = [], 0
        for day in range(1, self.settings.days + 1):
            jitter = JITTER * (2 * unit(self.settings.seed, "size", lane.position, day) - 1)
            size = max(1, round(lane.ips * (1 + jitter)))
            start = max(0, end - round(lane.reuse * size)) if day > 1 else 0
            windows.append((start, size))
            end = start + size
        return windows

    def _places(self) -> list[Places]:
        """City, region and ASN lists per country, sized from its largest test (DB-IP-like)."""
        places, location, network = [], 2, 2  # id 1 is the unknown member of both lists
        count = len(self.settings.countries)
        for c in range(count):
            largest = max(self.lanes[n * count + c].ips for n in range(len(self.formulas)))
            cities = min(5000, max(MIN_CITIES, round(largest / 12)))
            asns = min(900, max(MIN_ASNS, cities // 6))
            places.append(Places(cities, min(60, max(1, cities // 40)), asns, location, network))
            location, network = location + cities, network + asns
        return places

    def lane(self, network: int, country: int) -> Lane:
        return self.lanes[network * len(self.settings.countries) + country]

    def window(self, lane: Lane, day: int) -> tuple[int, int]:
        """(first position, size) of the lane's own IPs on a day."""
        return self.windows[lane.position][day - 1]

    def new(self, lane: Lane, day: int) -> tuple[int, int]:
        """Positions [first, after) the lane uses for the first time on a day (maybe empty).

        Windows only move forward, so these ranges never overlap and together are every
        position the lane has used.
        """
        seen = max((sum(self.window(lane, d)) for d in range(1, day)), default=0)
        start, size = self.window(lane, day)
        return max(seen, start), max(seen, start + size)

    def neighbour(self, lane: Lane) -> Lane | None:
        count = len(self.settings.countries)
        return self.lane(lane.network, (lane.country + 1) % count) if count > 1 else None

    def runs_per_day(self) -> int:
        return len(self.lanes) * 25  # one daily test and 24 pulses per lane

    def run_key(self, day: int, index: int) -> int:
        return (day - 1) * self.runs_per_day() + index + 1

    def test(self, lane: Lane, day: int) -> Test:
        start, size = self.window(lane, day)
        other, borrowed, source = self.neighbour(lane), 0, 0
        if other is not None:
            other_start, other_size = self.window(other, day)
            borrowed = min(round(SHARED * size), other_size)
            source = other.offset + other_start
        seed = self.settings.seed
        minute = 5 * (1 + key(seed, "minute", lane.position, day) % 8)
        started = self.settings.day_start(day) + timedelta(hours=lane.hour, minutes=minute)
        ips = size + borrowed
        rows = ips + (ips + 2) // 3
        successes = max(rows, round(lane.ratio * ips))
        buckets = 2 + key(seed, "buckets", lane.position, day) % 3
        run_key = self.run_key(day, lane.position)
        return Test(lane, day, run_key, start, size, borrowed, source, buckets, started, successes)

    def enrichment(self, n: int, places: Places) -> tuple[int, int, bool]:
        """(location_id, network_id, matched) of IP index n owned by a country."""
        value = mix(n ^ self.salt)
        if value % 1000 < UNMATCHED:
            return 1, 1, False
        city = skewed(value >> 16, places.cities)
        return places.location + city, places.network + skewed(value >> 40, places.asns), True

    def latency(self, network: int) -> list[int]:
        """The millisecond bins of a network (its median from the seed)."""
        median = 250 + 900 * unit(self.settings.seed, "latency", network)
        return [math.ceil(median * factor) for factor in LATENCY]

    def formula(self, lane: Lane) -> dict:
        """The network's formula with the lane's country entry (for estimates.compute)."""
        country = self.settings.countries[lane.country]
        return self.formulas[lane.network] | {"countries": {country: lane.entry}}

    def estimates(self, test: Test) -> list[dict]:
        """The estimated hours of a daily test, as `daily ingest` stores them."""
        country = self.settings.countries[test.lane.country]
        found = compute.hours(
            self.formula(test.lane), country, test.started_at, test.ips, test.successes
        )
        return [row for row in found if row["estimated"]]

    def pulse(self, lane: Lane, day: int, hour: int) -> tuple[int, list[tuple]]:
        """Timeouts and geo rows (location, network, completed, successes, ms) of one pulse."""
        seed = key(self.settings.seed, "pulse", lane.position, day, hour)
        places = self.places[lane.country]
        errors, wanted = seed % 4, GEO_ROWS[0] + (seed >> 8) % (GEO_ROWS[1] - GEO_ROWS[0] + 1)
        known = wanted - (errors > 0)  # places hold at least MIN_CITIES x MIN_ASNS pairs
        pairs, value = [], seed
        taken = set()
        while len(pairs) < known:
            value = mix(value)
            city, asn = skewed(value, places.cities), skewed(value >> 32, places.asns)
            while (city, asn) in taken:
                asn = (asn + 1) % places.asns
                city = (city + (asn == 0)) % places.cities
            taken.add((city, asn))
            pairs.append((places.location + city, places.network + asn))
        bins = self.latency(lane.network)
        shares = apportion(PULSE_REQUESTS - errors, [1] * known)
        rows = [
            (loc, net, n, n, bins[mix(seed + i) % len(bins)])
            for i, ((loc, net), n) in enumerate(zip(pairs, shares, strict=True))
        ]
        if errors:
            rows.append((1, 1, errors, 0, None))
        return errors, rows


def _fallback(formula: dict) -> tuple[int, float]:
    """Unique IPs and requests for a country the formula lacks: its small countries' figures."""
    measured = sorted(
        (entry["unique_ips"][hour], entry["requests"][hour] or 0)
        for country, hour in formula["schedule"].items()
        if (entry := formula["countries"].get(country)) and entry["unique_ips"][hour]
    )
    if not measured:
        return 100, 200.0
    return measured[int(len(measured) * FALLBACK_QUANTILE)]
