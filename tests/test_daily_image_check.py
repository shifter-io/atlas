"""IMAGE-AUTO-1: `atlas daily image` checks the worker image against the code (daily.image_check):
the image's locked dependencies against current.json's, and its DB-IP release's age. Fake
manager files only; nothing leaves the machine."""

from __future__ import annotations

import json
from datetime import UTC, datetime, timedelta

import pytest
from daily_cases import template

from atlas.campaign.current_wheel import requirements_fingerprint
from atlas.cli import main
from atlas.daily.image_check import MMDB_AGE, ImageFiles, checks

NOW = datetime(2027, 1, 20, 12, tzinfo=UTC)
NAME = "atlas-camp-worker-x"  # campaign_hour_cases.make_spec's image_name
LOCKED = requirements_fingerprint("aiohttp==3.14.3\n")


def manager(tmp_path, *, code=LOCKED, **build):
    """The template, an inventory with one built record of its image, and current.json."""
    root = template(tmp_path)
    record = {
        "started_at": (NOW - timedelta(days=3)).isoformat(),
        "state": "built",
        "snapshot_name": NAME,
        "requirements_sha256": LOCKED,
        "mmdb_sha256": "a" * 64,
        "mmdb_built_at": (NOW - timedelta(days=10)).isoformat(),
    } | build
    images = tmp_path / "campaign-images.json"
    old = {"started_at": "2026-01-01T00:00:00+00:00", "state": "failed", "snapshot_name": NAME}
    images.write_text(json.dumps({"builds": [old, {k: v for k, v in record.items() if v}]}))
    wheels = tmp_path / "wheels"
    wheels.mkdir()
    if code:
        (wheels / "current.json").write_text(json.dumps({"requirements_sha256": code}))
    return ImageFiles(root, images, wheels)


def verdicts(files):
    return [(c.subject, c.ok, c.detail) for c in checks(files, NOW)]


def test_an_image_that_fits_the_code_is_ok(tmp_path):
    assert verdicts(manager(tmp_path)) == [
        ("dependencies", True, f"the code's ({LOCKED[:12]})"),
        ("db-ip", True, "release 10 days old"),
    ]


def test_changed_locked_dependencies_ask_for_a_rebuild(tmp_path):
    files = manager(tmp_path, code=requirements_fingerprint("aiohttp==3.15.0\n"))
    assert verdicts(files)[0] == (
        "dependencies",
        False,
        "the code's locked dependencies changed: rebuild",
    )


def test_the_fingerprint_ignores_the_export_header():
    header = "# This file was autogenerated by uv via the following command:\n#    uv export\n"
    assert requirements_fingerprint(header + "\naiohttp==3.14.3\n") == LOCKED


@pytest.mark.parametrize(
    ("change", "missing"),
    [({"requirements_sha256": None}, "the image"), ({"code": None}, "current.json")],
)
def test_nothing_to_compare_is_ok_and_says_so(tmp_path, change, missing):
    (subject, ok, detail), _ = verdicts(manager(tmp_path, **change))
    assert (subject, ok, detail) == ("dependencies", True, f"not compared: {missing} records none")


def test_an_old_db_ip_release_asks_for_a_rebuild(tmp_path):
    old = (NOW - MMDB_AGE - timedelta(days=1)).isoformat()
    assert verdicts(manager(tmp_path, mmdb_built_at=old))[1] == (
        "db-ip",
        False,
        "release 36 days old, over 35: rebuild",
    )


def test_without_a_release_date_the_build_date_stands_in(tmp_path):
    started = (NOW - timedelta(days=40)).isoformat()
    files = manager(tmp_path, mmdb_built_at=None, started_at=started)
    assert verdicts(files)[1] == ("db-ip", False, "built 40 days ago, over 35: rebuild")


def test_an_image_without_a_database_fails(tmp_path):
    assert verdicts(manager(tmp_path, mmdb_sha256=None))[1] == (
        "db-ip",
        False,
        "the image holds no DB-IP database",
    )


def test_no_built_record_of_the_template_image_fails(tmp_path):
    files = manager(tmp_path, snapshot_name="atlas-camp-worker-other")
    assert verdicts(files) == [("record", False, f"no built record of {NAME} in the inventory")]


def test_an_unreadable_inventory_fails_naming_no_path(tmp_path):
    files = manager(tmp_path)
    files.images.write_text("{not json")
    [(subject, ok, detail)] = verdicts(files)
    assert (subject, ok) == ("record", False) and str(tmp_path) not in detail


def test_the_command_prints_one_line_per_check_and_exits_3_on_a_failure(tmp_path, capsys):
    files = manager(tmp_path, code=requirements_fingerprint("other==1\n"))
    argv = ["daily", "image", "--template", str(files.template), "--images", str(files.images)]
    assert main([*argv, "--wheels", str(files.wheels)]) == 3
    lines = capsys.readouterr().out.splitlines()
    assert lines[0] == "dependencies\tfailed\tthe code's locked dependencies changed: rebuild"
    assert lines[1].startswith("db-ip\tok\trelease ")
